"""Export the coastal-buffer study area and isobaths to study_area_data.js for the maps in index.html.

    python fetch_env_data.py --bathy --out real_env
    python export_study_area_web.py

The study area is the ocean within RegionConfig.coastal_buffer_km (50 km) of the coastline,
both taken from the real bathymetry (ETOPO 2022 / GEBCO) the simulator and models use.
"""
from pathlib import Path
import argparse
import json
from datetime import date

import numpy as np
from contourpy import FillType, LineType, contour_generator

from web_stamp import stamp_index
from purse_seine_sim.config import RegionConfig
from purse_seine_sim.geo import KM_PER_DEG_LAT, Geography, km_per_deg_lon

BATHY_FILE = Path("real_env/bathy.npz")
OUT_FILE = Path("study_area_data.js")
ISOBATHS_M = [10, 20, 30, 50, 70]
MIN_RING_POINTS = 8         # drop specks (single-cell islands, pits) from the outline


def thin(points, step_deg=0.008):
    """Drop points closer than step_deg to the last kept one; keeps the ring closed."""
    keep = [points[0]]
    for p in points[1:-1]:
        if np.abs(p - keep[-1]).max() >= step_deg:
            keep.append(p)
    keep.append(points[-1])
    return np.array(keep)


def latlon(points):
    return [[round(float(y), 3), round(float(x), 3)] for x, y in points]


def buffer_polygons(geo, buffer_km):
    """Polygons [[outer ring], [hole], ...] of the 0..buffer_km band, as [lat, lon] rings."""
    # -1 on land, distance (km) in the study area, far away elsewhere at sea:
    # the -0.5 contour is the coastline, buffer_km the outer edge.
    field = np.where(geo.land, -1.0, np.where(geo.study_area, geo.dist_coast_km, 1e4))
    gen = contour_generator(geo.lons, geo.lats, field, fill_type=FillType.OuterOffset)
    points, offsets = gen.filled(-0.5, buffer_km)
    polys = []
    for pts, off in zip(points, offsets):
        rings = [thin(pts[a:b]) for a, b in zip(off[:-1], off[1:])]
        rings = [r for r in rings if len(r) >= MIN_RING_POINTS]
        if rings and len(pts[off[0]:off[1]]) >= MIN_RING_POINTS:
            polys.append([latlon(r) for r in rings])
    return polys


def isobaths(bathy_path, region):
    """Depth contours on the native bathymetry grid, cut to the region."""
    b = np.load(bathy_path)
    lat, lon, elev = b["lat"], b["lon"], b["elevation"].astype(float)
    i = (lat >= region.lat_min) & (lat <= region.lat_max)
    j = (lon >= region.lon_min) & (lon <= region.lon_max)
    depth = np.ma.masked_where(elev[np.ix_(i, j)] >= 0, -elev[np.ix_(i, j)])
    gen = contour_generator(lon[j], lat[i], depth, line_type=LineType.Separate)
    out = []
    for level in ISOBATHS_M:
        lines = [latlon(thin(seg)) for seg in gen.lines(level) if len(seg) >= MIN_RING_POINTS]
        if lines:
            out.append({"depth_m": level, "lines": lines})
    return out, str(b["source"]) if "source" in b.files else bathy_path.name


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--bathy", default=str(BATHY_FILE))
    p.add_argument("--out", default=str(OUT_FILE))
    a = p.parse_args()
    bathy_path, out_file = Path(a.bathy), Path(a.out)
    if not bathy_path.exists():
        raise FileNotFoundError(f"{bathy_path} not found: run `python fetch_env_data.py --bathy --out real_env` first")

    region = RegionConfig(bathy_npz=str(bathy_path))
    geo = Geography(region, np.random.default_rng(0))
    cell_km2 = (region.grid_res_deg * KM_PER_DEG_LAT) * (region.grid_res_deg * km_per_deg_lon(geo.LAT))
    inside = geo.study_area
    lines, source = isobaths(bathy_path, region)
    payload = {
        "meta": {"generated": date.today().isoformat(), "source": source, "buffer_km": region.coastal_buffer_km,
                 "area_km2": round(float(cell_km2[inside].sum())),
                 "mean_depth_m": round(float(np.nanmean(geo.depth_m[inside])), 1),
                 "max_depth_m": round(float(np.nanmax(geo.depth_m[inside])), 1),
                 "bounds": [[region.lat_min, region.lon_min], [region.lat_max, region.lon_max]]},
        "buffer": buffer_polygons(geo, region.coastal_buffer_km),
        "isobaths": lines,
    }
    js = ("/* Generated by export_study_area_web.py: do not edit by hand. */\n"
          "window.STUDY_AREA = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n")
    out_file.write_text(js, encoding="utf-8")
    stamp_index(out_file)
    m = payload["meta"]
    print(f"Created: {out_file.resolve()} ({out_file.stat().st_size / 1024:.0f} KB)")
    print(f"Study area: 0-{m['buffer_km']:.0f} km, {m['area_km2']:,} km2, depth mean {m['mean_depth_m']} m, "
          f"max {m['max_depth_m']} m | {len(payload['buffer'])} polygons | isobaths "
          + ", ".join(f"{iso['depth_m']} m" for iso in lines))


if __name__ == "__main__":
    main()
